<?php

namespace App\Command;

use App\Service\LegacyUserFlightReportComparator;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Input\InputArgument;
use Symfony\Component\Console\Input\InputInterface;
use Symfony\Component\Console\Input\InputOption;
use Symfony\Component\Console\Output\OutputInterface;
use Symfony\Component\Console\Style\SymfonyStyle;

final class CompareLegacyUserPostflightCommand extends Command
{
    protected static $defaultName = 'app:user:compare-postflight';

    private LegacyUserFlightReportComparator $comparator;

    public function __construct(LegacyUserFlightReportComparator $comparator)
    {
        parent::__construct();
        $this->comparator = $comparator;
    }

    protected function configure(): void
    {
        $this
            ->setDescription('Compares target postflight counts with the canonical legacy-user preflight report.')
            ->setHelp('Generated timestamps and report wrapper versions are ignored. Record schema, overall counts, and oldUid cohorts must match exactly.')
            ->addArgument('preflight', InputArgument::REQUIRED, 'Preflight JSON generated by app:user:export-preflight.')
            ->addArgument('postflight', InputArgument::REQUIRED, 'Postflight JSON generated from the Firebase destination.')
            ->addOption('output', 'o', InputOption::VALUE_REQUIRED, 'Write the comparison report to a new file instead of standard output.');
    }

    protected function execute(InputInterface $input, OutputInterface $output): int
    {
        $io = new SymfonyStyle($input, $output);

        try {
            $preflight = $this->readReport((string) $input->getArgument('preflight'));
            $postflight = $this->readReport((string) $input->getArgument('postflight'));
            $comparison = $this->comparator->compare(
                $preflight,
                $postflight,
                new \DateTimeImmutable('now', new \DateTimeZone('UTC'))
            );
            $json = json_encode($comparison, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR)."\n";

            $outputPath = $input->getOption('output');
            if (null === $outputPath) {
                $output->write($json);
            } else {
                $this->writeNewFile((string) $outputPath, $json);
            }

            return $comparison['matches'] ? Command::SUCCESS : Command::FAILURE;
        } catch (\Throwable $exception) {
            $io->error($exception->getMessage());

            return Command::FAILURE;
        }
    }

    private function readReport(string $path): array
    {
        $contents = @file_get_contents($path);
        if (false === $contents) {
            throw new \RuntimeException(sprintf('Unable to read report: %s', $path));
        }

        $report = json_decode($contents, true, 512, JSON_THROW_ON_ERROR);
        if (!is_array($report)) {
            throw new \UnexpectedValueException(sprintf('Report must contain a JSON object: %s', $path));
        }

        return $report;
    }

    private function writeNewFile(string $path, string $contents): void
    {
        $handle = @fopen($path, 'x');
        if (false === $handle) {
            throw new \RuntimeException(sprintf('Unable to create comparison report; the path may already exist: %s', $path));
        }

        try {
            if (strlen($contents) !== fwrite($handle, $contents)) {
                throw new \RuntimeException(sprintf('Unable to write complete comparison report: %s', $path));
            }
        } catch (\Throwable $exception) {
            fclose($handle);
            if (is_file($path)) {
                unlink($path);
            }
            throw $exception;
        } finally {
            if (is_resource($handle)) {
                fclose($handle);
            }
        }
    }
}
